#!/usr/bin/env node
/**
 * Writes src/googleSecret.js from the environment. Run before packaging.
 *
 *   WITHY_GOOGLE_CLIENT_ID=... WITHY_GOOGLE_CLIENT_SECRET=... \
 *     node scripts/write-google-secret.js
 *
 * The output is gitignored: an installed-app client secret has to ship inside
 * the binary, but that is no reason to put it in a public repo's history —
 * GitHub push protection blocks it anyway. CI supplies the same two values
 * from repository secrets.
 */
const fs = require('node:fs');
const path = require('node:path');

const clientId = process.env.WITHY_GOOGLE_CLIENT_ID || '';
const clientSecret = process.env.WITHY_GOOGLE_CLIENT_SECRET || '';

if (!clientId || !clientSecret) {
  console.error('WITHY_GOOGLE_CLIENT_ID / WITHY_GOOGLE_CLIENT_SECRET are required');
  process.exit(1);
}

const out = path.join(__dirname, '..', 'src', 'googleSecret.js');
const body = "'use strict';\n// Generated by scripts/write-google-secret.js - do not commit.\n"
  + 'module.exports = ' + JSON.stringify({ clientId, clientSecret }, null, 2) + ';\n';
fs.writeFileSync(out, body);
console.log('wrote src/googleSecret.js');
